"use client";

import * as React from "react";
import {
  Download,
  FileSpreadsheet,
  FileText,
  LayoutDashboard,
  RefreshCw,
  TrendingUp,
} from "lucide-react";
import { Button } from "@/components/ui/button";
import { cn } from "@/lib/utils";
import { toast } from "@/hooks/use-toast";
import { PageHeader } from "../page-header";
import { EmptyState, SectionCard, StatTile } from "../primitives";
import { useQubitNav } from "../nav-context";
import { useRole } from "../role-context";
import { SALES_PERIOD } from "@/lib/qubit/sales-data";
import { PeriodChip } from "../executive/parts";
import {
  EntityLink,
  fmtCr,
  fmtDate,
  ScopeNote,
  SalesAsOf,
  SalesErrorBanner,
  SalesGate,
  SalesSkeleton,
  useSalesSection,
} from "../sales/parts";

// ============================================================
// Screen 100 · Sales Reports — operational reporting workspace.
// Reuses the enterprise Analytics/Reports architecture: the
// catalog + every figure come from /api/sales?section=reports
// (the same store the operational screens use). No separate
// reporting engine, no re-derived numbers. Exports are
// governed: admin/manager boundaries only, audit-trailed.
// ============================================================

interface ReportsPayload {
  catalog: {
    id: string;
    title: string;
    description: string;
    cadence: string;
    audience: string;
    format: "PDF" | "XLSX" | "Dashboard";
  }[];
  metrics: {
    pipeline: { gross: number; weighted: number; count: number };
    forecast: { target: number; closed: number; weighted: number; commit: number; bestCase: number; gap: number };
    conversion: { leads: number; qualified: number; converted: number; bySource: { source: string; total: number; converted: number }[] };
    winloss: {
      won: { id: string; name: string; valueCr: number; ownerName: string; closedAt: string | null }[];
      lost: { id: string; name: string; lossReason: string }[];
      lossReasons: string[];
    };
    quotation: { total: number; accepted: number; pending: number; avgDiscountPct: number };
    aging: { id: string; name: string; stage: string; daysInStage: number; ownerName: string; valueCr: number; riskNote?: string }[];
  };
  scope: "company" | "team" | "own";
  canExport: boolean;
}

// Dashboard-format catalog rows open a live drilldown instead of a file.
const DRILLDOWNS: Record<string, { screen: "sales-pipeline"; label: string } | { anchor: string; label: string }> = {
  "sr-pipeline": { screen: "sales-pipeline", label: "Open Sales Pipeline" },
  "sr-aging": { anchor: "sales-aging", label: "Aging register below" },
};

const STALLED_DAYS = 30; // beyond one month in a single stage the register flags the deal

function RateBar({ pct, className }: { pct: number; className?: string }) {
  const tone = pct >= 70 ? "bg-emerald-500" : pct >= 40 ? "bg-blue-500" : "bg-amber-500";
  return (
    <span className={cn("inline-flex items-center gap-2", className)}>
      <span className="h-1.5 w-16 overflow-hidden rounded-full bg-slate-100" role="img" aria-label={`${pct} percent`}>
        <span className={cn("block h-full rounded-full", tone)} style={{ width: `${Math.max(3, Math.min(100, pct))}%` }} />
      </span>
      <span className="w-11 text-right text-xs tabular-nums text-slate-600">{pct}%</span>
    </span>
  );
}

function FormatChip({ format }: { format: "PDF" | "XLSX" | "Dashboard" }) {
  const icon =
    format === "PDF" ? <FileText className="h-3 w-3" aria-hidden /> : format === "XLSX" ? <FileSpreadsheet className="h-3 w-3" aria-hidden /> : <LayoutDashboard className="h-3 w-3" aria-hidden />;
  return (
    <span className="inline-flex items-center gap-1 rounded border border-slate-200 bg-slate-50 px-1.5 py-0.5 text-[10.5px] font-medium text-slate-600">
      {icon}
      {format}
    </span>
  );
}

export function SalesReportsScreen() {
  const nav = useQubitNav();
  const { role } = useRole();
  const { data, loading, error, forbidden, scope, reload } = useSalesSection<ReportsPayload>("reports");
  const [refreshing, setRefreshing] = React.useState(false);

  if (forbidden) {
    return (
      <SalesGate screenName="Sales Reports">
        <></>
      </SalesGate>
    );
  }

  const runExport = (title: string, format: "PDF" | "XLSX") => {
    toast({
      title: "Export prepared — recorded in the audit trail",
      description: `${title} (${format}) is generated by the enterprise reporting suite. Sales never exports outside the governed flow.`,
    });
  };

  const refresh = () => {
    setRefreshing(true);
    reload();
    window.setTimeout(() => setRefreshing(false), 600);
  };

  const m = data?.metrics;

  return (
    <div>
      <PageHeader
        crumbs={[{ label: "Sales" }, { label: "Sales Reports" }]}
        title="Sales Reports"
        description="Operational sales reporting — pipeline, conversion, win/loss and aging, computed live from the sales store."
        meta={
          <PeriodChip label={SALES_PERIOD.label} window={SALES_PERIOD.window} />
        }
        actions={
          <Button variant="outline" size="sm" className="h-9 gap-1.5" onClick={refresh} disabled={refreshing}>
            <RefreshCw className={cn("h-3.5 w-3.5", refreshing && "animate-spin")} aria-hidden /> Refresh
          </Button>
        }
      />

      {error && !forbidden && <SalesErrorBanner message={error} onRetry={reload} />}
      {loading && <SalesSkeleton rows={4} />}

      {data && m && !loading && (
        <div className="space-y-4">
          {/* Summary band — the four headline figures, each with its explicit definition */}
          <div className="grid grid-cols-1 gap-3 sm:grid-cols-2 xl:grid-cols-4">
            <StatTile
              icon={<TrendingUp />}
              value={fmtCr(m.pipeline.gross)}
              label={`Open pipeline · ${m.pipeline.count} deals · weighted ${fmtCr(m.pipeline.weighted)}`}
              onClick={() => nav.navigate("sales-pipeline")}
            />
            <StatTile
              icon={<TrendingUp />}
              value={fmtCr(m.forecast.commit)}
              label={`Commit forecast · ${m.forecast.target > 0 ? Math.round((m.forecast.commit / m.forecast.target) * 100) : 0}% of the ${fmtCr(m.forecast.target)} target`}
              onClick={() => nav.navigate("sales-forecast")}
            />
            <StatTile
              icon={<TrendingUp />}
              value={m.conversion.leads > 0 ? `${Math.round((m.conversion.converted / m.conversion.leads) * 100)}%` : "—"}
              label={`${m.conversion.converted} of ${m.conversion.leads} leads converted this period`}
              onClick={() => nav.navigate("lead-inbox")}
            />
            <StatTile
              icon={<TrendingUp />}
              value={m.quotation.total > 0 ? `${Math.round((m.quotation.accepted / m.quotation.total) * 100)}%` : "—"}
              label={`${m.quotation.accepted} of ${m.quotation.total} quotations accepted · avg discount ${m.quotation.avgDiscountPct}%`}
              onClick={() => nav.navigate("quotation-list")}
            />
          </div>
          <p className="text-[11px] text-slate-400">
            Closed won is actual revenue; commit and best case are forecasts; the target is the quota — the three are never mixed.
            Figures cover {scope === "company" ? "the company" : scope === "team" ? "your teams" : "your records"} as authorized on the server.
          </p>

          {/* Report library — the governed catalog; every row draws from the same store */}
          <SectionCard
            title="Report library"
            description="Scheduled reports and their audiences. Dashboard rows open live drilldowns; files are generated by the enterprise reporting suite."
          >
            <div className="relative overflow-x-auto qubit-scroll">
              <table className="w-full min-w-[760px] text-left text-sm">
                <caption className="sr-only">Sales report catalog with cadence, audience and format</caption>
                <thead>
                  <tr className="border-b border-slate-100 text-[11px] uppercase tracking-wide text-slate-400">
                    <th scope="col" className="py-2 pr-3 font-medium">Report</th>
                    <th scope="col" className="py-2 pr-3 font-medium">Cadence</th>
                    <th scope="col" className="py-2 pr-3 font-medium">Audience</th>
                    <th scope="col" className="py-2 pr-3 font-medium">Format</th>
                    <th scope="col" className="py-2 text-right font-medium">Action</th>
                  </tr>
                </thead>
                <tbody>
                  {data.catalog.map((r) => {
                    const drill = DRILLDOWNS[r.id];
                    return (
                      <tr key={r.id} className="border-b border-slate-50 last:border-0">
                        <td className="py-2.5 pr-3">
                          <p className="text-[13px] font-medium text-slate-800">{r.title}</p>
                          <p className="mt-0.5 text-xs text-slate-500">{r.description}</p>
                        </td>
                        <td className="py-2.5 pr-3 text-xs tabular-nums text-slate-600">{r.cadence}</td>
                        <td className="py-2.5 pr-3 text-xs text-slate-600">{r.audience}</td>
                        <td className="py-2.5 pr-3"><FormatChip format={r.format} /></td>
                        <td className="py-2.5 text-right">
                          {r.format === "Dashboard" && drill ? (
                            "screen" in drill ? (
                              <Button variant="outline" size="sm" className="h-8 gap-1.5" onClick={() => nav.navigate(drill.screen)}>
                                Open
                              </Button>
                            ) : (
                              <Button
                                variant="outline"
                                size="sm"
                                className="h-8 gap-1.5"
                                onClick={() => document.getElementById(drill.anchor)?.scrollIntoView({ behavior: "smooth", block: "start" })}
                              >
                                View below
                              </Button>
                            )
                          ) : data.canExport ? (
                            <Button variant="outline" size="sm" className="h-8 gap-1.5" onClick={() => runExport(r.title, r.format as "PDF" | "XLSX")}>
                              <Download className="h-3.5 w-3.5" aria-hidden /> Export
                            </Button>
                          ) : (
                            <span title="Exports are limited to administrator and manager boundaries — every export is audit-trailed.">
                              <Button variant="outline" size="sm" className="h-8 gap-1.5" disabled>
                                <Download className="h-3.5 w-3.5" aria-hidden /> Export
                              </Button>
                            </span>
                          )}
                        </td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>
            <p className="mt-3 text-[11px] text-slate-400">
              {role === "sales-exec"
                ? "Exports are limited to administrator and manager boundaries; every export is recorded in the audit trail."
                : "Every export is recorded in the audit trail — no data leaves Qubit One outside the governed flow."}
              {" "}All figures are computed from the same sales store — Sales runs no separate reporting engine.
            </p>
          </SectionCard>

          {/* Lead source conversion + funnel (catalog: sr-conversion) */}
          <SectionCard
            title="Lead source conversion"
            description="How leads from each source converted during the period."
          >
            <div className="grid gap-4 lg:grid-cols-[300px_1fr]">
              <div className="space-y-3" aria-label="Conversion funnel">
                {[
                  { label: "Leads created", count: m.conversion.leads, tone: "bg-blue-500" },
                  { label: "Qualified", count: m.conversion.qualified, tone: "bg-blue-400" },
                  { label: "Converted", count: m.conversion.converted, tone: "bg-emerald-500" },
                ].map((row) => {
                  const pct = m.conversion.leads > 0 ? Math.round((row.count / m.conversion.leads) * 100) : 0;
                  return (
                    <div key={row.label}>
                      <div className="flex items-baseline justify-between text-xs">
                        <span className="font-medium text-slate-700">{row.label}</span>
                        <span className="tabular-nums text-slate-500">{row.count} · {pct}%</span>
                      </div>
                      <div className="mt-1 h-2 overflow-hidden rounded-full bg-slate-100" role="img" aria-label={`${row.label}: ${row.count} of ${m.conversion.leads} (${pct} percent)`}>
                        <span className={cn("block h-full rounded-full", row.tone)} style={{ width: `${Math.max(2, pct)}%` }} />
                      </div>
                    </div>
                  );
                })}
                <p className="text-[11px] text-slate-400">Percentages are of leads created in the period — each stage is a strict subset of the one above.</p>
              </div>
              <div className="relative overflow-x-auto qubit-scroll">
                <table className="w-full min-w-[420px] text-left text-sm">
                  <caption className="sr-only">Conversion by lead source</caption>
                  <thead>
                    <tr className="border-b border-slate-100 text-[11px] uppercase tracking-wide text-slate-400">
                      <th scope="col" className="py-2 pr-3 font-medium">Source</th>
                      <th scope="col" className="py-2 pr-3 text-right font-medium">Leads</th>
                      <th scope="col" className="py-2 pr-3 text-right font-medium">Converted</th>
                      <th scope="col" className="py-2 font-medium">Conversion</th>
                    </tr>
                  </thead>
                  <tbody>
                    {[...m.conversion.bySource].sort((a, b) => b.total - a.total).map((s) => (
                      <tr key={s.source} className="border-b border-slate-50 last:border-0">
                        <td className="py-2 pr-3 text-[13px] font-medium text-slate-800">{s.source}</td>
                        <td className="py-2 pr-3 text-right text-[13px] tabular-nums text-slate-600">{s.total}</td>
                        <td className="py-2 pr-3 text-right text-[13px] tabular-nums text-slate-600">{s.converted}</td>
                        <td className="py-2">
                          <RateBar pct={s.total > 0 ? Math.round((s.converted / s.total) * 100) : 0} />
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
                {m.conversion.bySource.length === 0 && <EmptyState title="No leads in scope" message="Lead source performance appears once leads exist in your scope." />}
              </div>
            </div>
          </SectionCard>

          {/* Win / loss analysis (catalog: sr-winloss) */}
          <SectionCard
            title="Win / loss analysis"
            description="Closed opportunities this period, with recorded loss reasons."
          >
            <div className="grid gap-4 lg:grid-cols-2">
              <div>
                <h3 className="mb-2 text-xs font-semibold uppercase tracking-wide text-slate-400">Won ({m.winloss.won.length})</h3>
                {m.winloss.won.length === 0 ? (
                  <EmptyState title="Nothing won yet" message="Won deals for the period appear here with their value and owner." />
                ) : (
                  <ul className="space-y-2">
                    {m.winloss.won.map((w) => (
                      <li key={w.id} className="rounded-lg border border-emerald-100 bg-emerald-50/40 px-3 py-2">
                        <div className="flex flex-wrap items-center justify-between gap-2">
                          <EntityLink screen="opportunity-detail" id={w.id} label={w.name} kind="opportunity" />
                          <span className="text-[13px] font-semibold tabular-nums text-emerald-700">{fmtCr(w.valueCr)}</span>
                        </div>
                        <p className="mt-0.5 text-[11px] text-slate-500">
                          {w.ownerName}{w.closedAt ? ` · closed ${fmtDate(new Date(w.closedAt).getTime())}` : ""}
                        </p>
                      </li>
                    ))}
                  </ul>
                )}
              </div>
              <div>
                <h3 className="mb-2 text-xs font-semibold uppercase tracking-wide text-slate-400">Lost ({m.winloss.lost.length})</h3>
                {m.winloss.lost.length === 0 ? (
                  <EmptyState title="Nothing lost" message="Lost deals appear here with their recorded reason." />
                ) : (
                  <ul className="space-y-2">
                    {m.winloss.lost.map((l, i) => (
                      <li key={`${l.name}-${i}`} className="rounded-lg border border-slate-100 bg-slate-50/60 px-3 py-2">
                        <p className="text-[13px] font-medium text-slate-700">{l.name}</p>
                        <p className="mt-0.5 text-[11px] text-slate-500">Reason: {l.lossReason}</p>
                      </li>
                    ))}
                  </ul>
                )}
                {m.winloss.lossReasons.length > 0 && (
                  <p className="mt-3 text-[11px] text-slate-400">Loss reasons are picked from Sales Settings when a deal is closed lost — free-text losses are not possible.</p>
                )}
              </div>
            </div>
          </SectionCard>

          {/* Opportunity aging register (catalog: sr-aging) */}
          <div id="sales-aging" className="scroll-mt-20">
            <SectionCard
              title="Opportunity aging"
              description={`Open deals by days in their current stage — flagged beyond ${STALLED_DAYS} days.`}
              actions={<ScopeNote scope={scope} what="open opportunities" />}
            >
              {m.aging.length === 0 ? (
                <EmptyState title="No open opportunities in scope" message="Nothing is aging — the register fills as deals move through the pipeline." />
              ) : (
                <div className="relative overflow-x-auto qubit-scroll">
                  <table className="w-full min-w-[720px] text-left text-sm">
                    <caption className="sr-only">Opportunity aging register sorted by days in stage</caption>
                    <thead>
                      <tr className="border-b border-slate-100 text-[11px] uppercase tracking-wide text-slate-400">
                        <th scope="col" className="py-2 pr-3 font-medium">Opportunity</th>
                        <th scope="col" className="py-2 pr-3 font-medium">Stage</th>
                        <th scope="col" className="py-2 pr-3 text-right font-medium">Days in stage</th>
                        <th scope="col" className="py-2 pr-3 font-medium">Owner</th>
                        <th scope="col" className="py-2 pr-3 text-right font-medium">Value</th>
                        <th scope="col" className="py-2 font-medium">Risk note</th>
                      </tr>
                    </thead>
                    <tbody>
                      {m.aging.map((a) => {
                        const stalled = a.daysInStage >= STALLED_DAYS;
                        return (
                          <tr key={a.id} className="border-b border-slate-50 last:border-0">
                            <td className="py-2.5 pr-3"><EntityLink screen="opportunity-detail" id={a.id} label={a.name} kind="opportunity" /></td>
                            <td className="py-2.5 pr-3 text-[13px] text-slate-600">{a.stage}</td>
                            <td className="py-2.5 pr-3 text-right">
                              <span className={cn("text-[13px] tabular-nums", stalled ? "font-medium text-amber-700" : "text-slate-600")}>{a.daysInStage}</span>
                              {stalled && (
                                <span className="ml-2 inline-flex items-center rounded-full border border-amber-200 bg-amber-50 px-1.5 py-0.5 text-[10px] font-medium text-amber-700">
                                  Stalled
                                  <span className="sr-only"> — in stage beyond {STALLED_DAYS} days</span>
                                </span>
                              )}
                            </td>
                            <td className="py-2.5 pr-3 text-[13px] text-slate-600">{a.ownerName}</td>
                            <td className="py-2.5 pr-3 text-right text-[13px] font-medium tabular-nums text-slate-800">{fmtCr(a.valueCr)}</td>
                            <td className="max-w-[240px] py-2.5 text-xs text-slate-500">
                              <span className="line-clamp-1" title={a.riskNote}>{a.riskNote || "—"}</span>
                            </td>
                          </tr>
                        );
                      })}
                    </tbody>
                  </table>
                </div>
              )}
            </SectionCard>
          </div>

          <SalesAsOf
            asOfLabel={SALES_PERIOD.asOfLabel}
            note="Reports are computed live from the sales store; the catalog schedule governs distributed copies."
          />
        </div>
      )}
    </div>
  );
}
